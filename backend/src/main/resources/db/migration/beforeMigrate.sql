-- Flyway runs before Hibernate, and V2 alters movies, so on an empty database V2 fails on a table nobody has created yet.
-- A callback, not a migration: it is not recorded or checksummed, so V1 to V4 stay byte-identical for existing databases.
-- Hibernate (ddl-auto=update) adds every other column after Flyway finishes. On an existing database this does nothing.
CREATE TABLE IF NOT EXISTS movies (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
